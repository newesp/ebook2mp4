"""Native voice layout; content state remains in VoiceDialog."""
import tkinter as tk
from tkinter import ttk
from .voice import EXAMPLE
from .workspace_layout import ProductionPageLayout, ToolbarLayout, TOOLBAR_GAP


class VoiceWorkspaceLayout(ProductionPageLayout):
    def __init__(layout, page, app):
        self = page
        self.columnconfigure(0, weight=1)
        self.rowconfigure(1, weight=1)
        service_panel = ttk.LabelFrame(self, text='選擇服務', padding=(16, 8))
        service_panel.grid(row=1, column=0, sticky='ew', padx=6, pady=(0, 6))
        self.rowconfigure(1, weight=0)
        self.rowconfigure(2, weight=1)
        self.sources_panel = ttk.Frame(self)
        self.sources_panel.grid(row=0, column=0, sticky='ew')
        self.sources_panel.columnconfigure(1, weight=1)
        ttk.Label(self.sources_panel, text='已存設定／歷史任務').grid(row=0, column=0, padx=(0, 8))
        self.source_choice = tk.StringVar()
        self.source_control = ttk.Combobox(self.sources_panel, textvariable=self.source_choice, state='readonly')
        self.source_control.grid(row=0, column=1, sticky='ew')
        self.source_button = ttk.Button(self.sources_panel, text='載入設定', command=self.load_selected_settings)
        self.source_button.grid(row=0, column=2, padx=(8, 0))
        self.loaded_run_id = None
        self.setting_sources = []
        service_panel.columnconfigure(1, weight=1)
        service_panel.columnconfigure(3, weight=1)
        ttk.Label(service_panel, text='服務').grid(row=0, column=0, padx=(0, 4))
        self.service = tk.StringVar(value='edge-tts')
        self.service_control = ttk.Combobox(service_panel, textvariable=self.service, state='readonly', width=16)
        self.service_control.grid(row=0, column=1, sticky='ew')
        self.service_control.bind('<<ComboboxSelected>>', self.change_service)
        ttk.Label(service_panel, text='模型（可選或輸入）').grid(row=0, column=2, padx=6)
        self.model = tk.StringVar()
        self.model_control = ttk.Combobox(service_panel, textvariable=self.model, width=16)
        self.model_control.grid(row=0, column=3, sticky='ew')
        self.manage_button = ttk.Menubutton(service_panel, text='新增／管理服務…')
        self.service_menu = tk.Menu(self.manage_button, tearoff=False, postcommand=self.update_service_menu)
        self.service_menu.add_command(label='新增服務…', command=self.manage_services)
        self.service_menu.add_command(label='編輯目前服務…', command=self.manage_current_service)
        self.manage_button.configure(menu=self.service_menu)
        self.manage_button.grid(row=0, column=4, padx=(12, 0))

        body = ttk.Frame(self)
        body.grid(row=2, column=0, sticky='nsew', padx=6)
        body.columnconfigure(0, weight=1, uniform='voice-body')
        body.columnconfigure(1, weight=2, uniform='voice-body')
        body.rowconfigure(0, weight=1)
        settings_panel = ttk.LabelFrame(body, text='設定聲音與節奏', padding=12)
        settings_panel.grid(row=0, column=0, sticky='nsew', padx=(0, 6))
        settings_panel.columnconfigure(0,weight=1)
        settings_panel.rowconfigure(0,weight=1)
        from .production_desktop import ScrollPage
        self.settings_scroll=ScrollPage(settings_panel)
        self.settings_scroll.grid(row=0,column=0,sticky='nsew')
        middle=self.settings_scroll.content
        middle.columnconfigure(0, weight=1)
        self.catalog_actions = ttk.Frame(middle)
        self.catalog_actions.grid(row=7, column=0, sticky='ew', pady=(0, 4))
        self.catalog_actions.columnconfigure(0, weight=1)
        self.locale = tk.StringVar(value='全部語系')
        self.filter = ttk.Combobox(self.catalog_actions, textvariable=self.locale,
                                  values=('全部語系', '台灣華語', '中國普通話', '英文'), state='readonly', width=10)
        self.filter.grid(row=0, column=0, sticky='ew', padx=(0, 4))
        self.filter.bind('<<ComboboxSelected>>', lambda e: self.load_catalog())
        self.refresh_button = ttk.Button(self.catalog_actions, text='更新線上音色', command=self.refresh_voices)
        self.refresh_button.grid(row=0, column=1)
        self.voice = tk.StringVar()
        self.voice_label = ttk.Label(middle, text='音色（可選或輸入 ID）')
        self.voice_label.grid(row=1, column=0, sticky='w')
        self.voice_entry = ttk.Entry(middle, textvariable=self.voice, width=18)
        self.voice_entry.grid(row=2, column=0, sticky='ew', pady=(2, 4))
        self.voice_control = ttk.Combobox(middle, textvariable=self.voice, width=18)
        self.voice_control.grid(row=2, column=0, sticky='ew', pady=(2, 4))
        self.cache_info = ttk.Label(middle, text='', wraplength=260)
        self.cache_info.grid(row=3, column=0, sticky='ew', pady=(0, 6))
        rhythm = ttk.Frame(middle)
        rhythm.grid(row=4, column=0, sticky='ew')
        rhythm.columnconfigure(0, weight=1)
        rhythm.columnconfigure(1, weight=1)
        ttk.Label(rhythm, text='語速').grid(row=0, column=0, sticky='w')
        ttk.Label(rhythm, text='節奏').grid(row=0, column=1, sticky='w', padx=(6, 0))
        self.rate = tk.StringVar(value='正常')
        self.rate_control = ttk.Combobox(rhythm, textvariable=self.rate,
                                        values=('-20%', '-10%', '正常', '+10%', '+20%'), state='readonly', width=7)
        self.rate_control.grid(row=1, column=0, sticky='ew', pady=2)
        self.rhythm = tk.StringVar(value='自然')
        self.rhythm_control = ttk.Combobox(rhythm, textvariable=self.rhythm,
                                          values=('自然', '舒緩', '自訂'), state='readonly', width=7)
        self.rhythm_control.grid(row=1, column=1, sticky='ew', padx=(6, 0), pady=2)
        self.rhythm_control.bind('<<ComboboxSelected>>', self.apply_rhythm)
        self.sentence_label=ttk.Label(rhythm,text='句尾停頓（ms）',justify='left')
        self.sentence_label.grid(row=2,column=0,sticky='w',pady=(6,0))
        self.paragraph_label=ttk.Label(rhythm,text='段落停頓（ms）',justify='left')
        self.paragraph_label.grid(row=2,column=1,sticky='w',padx=(6,0),pady=(6,0))
        self.sentence_pause = tk.StringVar(value='0')
        self.paragraph_pause = tk.StringVar(value='500')
        self.sentence_control = ttk.Spinbox(rhythm, from_=0, to=1500, textvariable=self.sentence_pause, width=6)
        self.sentence_control.grid(row=3, column=0, sticky='ew', pady=2)
        self.paragraph_control = ttk.Spinbox(rhythm, from_=0, to=3000, textvariable=self.paragraph_pause, width=6)
        self.paragraph_control.grid(row=3, column=1, sticky='ew', padx=(6, 0), pady=2)
        self.rules_info = ttk.Label(middle, text='相同邊界取較長停頓；最後不補靜音。', wraplength=260)
        self.rules_info.grid(row=5, column=0, sticky='ew', pady=(6, 0))
        self.rate_info = ttk.Label(middle, text='', wraplength=260)
        self.rate_info.grid(row=6, column=0, sticky='ew', pady=(4, 0))

        controls = ttk.LabelFrame(body, text='編輯文字並試聽', padding=(12, 6))
        controls.grid(row=0, column=1, sticky='nsew')
        controls.columnconfigure(0, weight=1)
        controls.rowconfigure(0, weight=1)
        self.preview_text_frame = text_frame = ttk.Frame(controls)
        text_frame.grid(row=1, column=0, sticky='nsew', pady=(2*TOOLBAR_GAP, 0))
        text_frame.columnconfigure(0, weight=1)
        text_frame.rowconfigure(0, weight=1)
        self.outgoing = tk.Text(text_frame, height=4, width=20, wrap='word', font=('Microsoft JhengHei', 11),undo=True)
        self.outgoing.insert('1.0', EXAMPLE)
        self.outgoing.bind('<<Modified>>', self.text_changed)
        text_tools = ttk.Frame(controls)
        text_tools.grid(row=0, column=0, sticky='new')
        text_frame.grid_configure(row=1)
        controls.rowconfigure(0, weight=0)
        controls.rowconfigure(1, weight=1)
        self.sample_text_button = ttk.Button(text_tools, text='使用固定試聽範例',
            command=lambda:self.replace_preview_text(EXAMPLE), style='Workspace.TButton')
        self.selected_text_button = ttk.Button(text_tools, text='帶入選取文字',
            command=self.selected_preview_text, style='Workspace.TButton')
        ToolbarLayout.equal_button_pair(text_tools, self.sample_text_button,
            self.selected_text_button, group='preview-text-actions')
        self.text_menu=tk.Menu(self.outgoing,tearoff=False)
        self.text_menu.add_command(label='使用固定試聽範例',command=lambda:self.replace_preview_text(EXAMPLE))
        self.text_menu.add_command(label='帶入主稿選取文字',command=self.selected_preview_text)
        self.outgoing.bind('<Button-3>',lambda e:self.text_menu.tk_popup(e.x_root,e.y_root))
        self.outgoing.bind('<Shift-F10>',lambda e:self.text_menu.tk_popup(self.outgoing.winfo_rootx()+12,self.outgoing.winfo_rooty()+12))
        self.outgoing.grid(row=0, column=0, sticky='nsew')
        from .ui_controls import AutoHideScrollbar
        text_scroll = AutoHideScrollbar(text_frame, command=self.outgoing.yview)
        text_scroll.grid(row=0, column=1, sticky='ns')
        def update_text_scroll(first, last):
            text_scroll.set(first, last)
            text_scroll.grid_remove() if float(first) <= 0 and float(last) >= 1 else text_scroll.grid()
        self.outgoing.configure(yscrollcommand=update_text_scroll)
        self.preview_text_scroll = text_scroll
        self.text_info = ttk.Label(controls, text='', wraplength=400)
        self.text_info.grid(row=2, column=0, sticky='ew')
        self.consent = tk.BooleanVar(value=True)
        self.consent_control = ttk.Checkbutton(controls, text='同意傳送試聽文字（可能計費）', variable=self.consent)
        self.consent_control.grid(row=3, column=0, sticky='w', pady=2)
        self.local_notice=ttk.Label(controls,text='文字僅在本機 CPU 處理，不會傳送至雲端。')
        actions = ttk.Frame(controls)
        actions.grid(row=4, column=0, sticky='ew')
        self.preview_button = ttk.Button(actions, text='產生並播放試聽', command=self.preview, style='Primary.TButton')
        self.preview_button.grid(row=0, column=0, pady=2)
        self.play_button = ttk.Button(actions, text='重播', command=self.play, width=5)
        self.play_button.grid(row=0, column=1, padx=4)
        self.stop_button = ttk.Button(actions, text='停止', command=self.stop, width=5)
        self.stop_button.grid(row=0, column=2)
        self.cancel_button = ttk.Button(actions, text='取消', command=self.cancel, width=5)
        self.cancel_button.grid(row=0, column=3, padx=(4, 0))
        self.result_info = ttk.Label(controls, text='', wraplength=400)
        self.result_info.grid(row=5, column=0, sticky='ew', pady=2)
        self.status = ttk.Label(controls, text='請選擇服務與音色。', wraplength=400)
        self.status.grid(row=6, column=0, sticky='ew', pady=2)
        self.progress = ttk.Progressbar(controls, mode='indeterminate')
        self.progress.grid(row=7, column=0, sticky='ew', pady=2)

        self.voice_footer = footer = app.shell.create_footer(self, padding=(0, 8))
        footer.columnconfigure(1, weight=1)
        footer.columnconfigure(4, weight=0)
        self.back_button = footer.button('← 返回文稿',lambda: self.app.show_step(1),role='back')
        self.back_button.grid(row=0, column=0, sticky='w')
        self.scope = tk.StringVar(value='本批次' if self.batch_id else '全書預設')
        self.scope_control = ttk.Combobox(footer, textvariable=self.scope,
            values=('本批次', '全書預設') if self.batch_id else ('全書預設',), state='readonly', width=9)
        self.scope_control.grid(row=0, column=2, padx=6)
        self.scope_control.bind('<<ComboboxSelected>>', lambda e: self.load_settings())
        self.scope_control.bind('<<ComboboxSelected>>', lambda e: self.refresh_setting_sources(), add='+')
        self.save_button = footer.button('只儲存設定',self.save)
        self.save_button.grid(row=0, column=3)
        self.produce_button = footer.button('前往音訊製做 →',self.save_and_produce,role='primary')
        self.produce_button.grid(row=0, column=5, sticky='e')
        ToolbarLayout.equal_button_pair(footer, self.save_button, self.produce_button,
            column=3, group='voice-commit-actions')
        self.apply_defaults_button = footer.button('套用到既有批次…',self.open_defaults)
        self.apply_defaults_button.grid(row=0, column=5, sticky='ew')

        self.settings_panel, self.preview_panel = settings_panel, controls
        middle.bind('<Configure>', self.reflow,add='+')
        settings_panel.bind('<Configure>',self.reflow,add='+')
        controls.bind('<Configure>', self.reflow)
        self.settings_scroll.bind_scroll()
        def workspace_styles(widget):
            if isinstance(widget, ttk.Combobox):widget.configure(style='Workspace.TCombobox')
            elif isinstance(widget, ttk.Spinbox):widget.configure(style='Workspace.TSpinbox')
            elif isinstance(widget, ttk.Entry):widget.configure(style='Workspace.TEntry')
            elif isinstance(widget, ttk.Menubutton):widget.configure(style='Workspace.TMenubutton')
            elif isinstance(widget, ttk.Button) and widget.cget('style') not in ('Primary.TButton','Destructive.TButton'):widget.configure(style='Workspace.TButton')
            for child in widget.winfo_children():workspace_styles(child)
        workspace_styles(self)
        workspace_styles(footer)
        super(VoiceWorkspaceLayout, layout).__init__(page, app, self.sources_panel, self.voice_footer, (
            ('back', self.back_button, lambda:app.show_step(1)),
            ('save', self.save_button, self.save),
            ('produce', self.produce_button, self.save_and_produce),
            ('defaults', self.apply_defaults_button, self.open_defaults)))
